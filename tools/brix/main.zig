//! brix: evaluate a .brix manifest to the plain data Steward reads.
//!
//!   brix <system.brix> <out.zon>    evaluate, check, write ZON (the build uses this)
//!   brix --check <system.brix>      evaluate and check only
//!   brix --print <system.brix>      evaluate, check, print the ZON
//!
//! "Check" is the whole manifest check: the same `schema.validate` Steward
//! runs at compile time, and that every protocol named exists in grain/proto.
//! Errors name the file, line and column, show the line, and say how to fix it.
const std = @import("std");
const brix = @import("brix");
const schema = @import("schema");
const proto = @import("proto");

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    var mode: enum { write, check, print } = .write;
    var rest = args[1..];
    if (rest.len > 0 and std.mem.eql(u8, rest[0], "--check")) {
        mode = .check;
        rest = rest[1..];
    } else if (rest.len > 0 and std.mem.eql(u8, rest[0], "--print")) {
        mode = .print;
        rest = rest[1..];
    }
    if (rest.len != @as(usize, if (mode == .write) 2 else 1)) {
        std.debug.print("usage: brix <system.brix> <out.zon> | brix --check <system.brix> | brix --print <system.brix>\n", .{});
        return 2;
    }
    const path = rest[0];
    const cwd = std.Io.Dir.cwd();
    const source = cwd.readFileAlloc(io, path, arena, .limited(1 << 20)) catch |e| {
        std.debug.print("{s}: cannot read ({s})\n", .{ path, @errorName(e) });
        return 1;
    };

    var err_buf: [4096]u8 = undefined;
    var stderr = std.Io.File.stderr().writer(io, &err_buf);
    const ew = &stderr.interface;

    var diag: brix.Diagnostic = .{};
    const r = brix.evaluate(schema.Manifest, arena, source, &diag) catch |e| switch (e) {
        error.Invalid => {
            try brix.render(ew, path, source, diag);
            try ew.flush();
            return 1;
        },
        else => return e,
    };

    var buf: [512]u8 = undefined;
    const problem: ?[]const u8 = schema.validate(r.value, &buf) orelse unknownProtocol(r.value, &buf);
    if (problem) |msg| {
        if (brix.locate(r.labels, msg)) |pos| {
            try brix.render(ew, path, source, .{ .pos = pos, .msg = msg });
        } else try ew.print("{s}: {s}\n", .{ path, msg });
        try ew.flush();
        return 1;
    }

    var out: std.Io.Writer.Allocating = .init(arena);
    try out.writer.print("// Generated by brix from {s}. Edit that file, not this one.\n", .{std.fs.path.basename(path)});
    try std.zon.stringify.serialize(r.value, .{ .emit_default_optional_fields = false }, &out.writer);
    try out.writer.writeByte('\n');
    switch (mode) {
        .check => {},
        .print => {
            var obuf: [4096]u8 = undefined;
            var stdout = std.Io.File.stdout().writer(io, &obuf);
            try stdout.interface.writeAll(out.written());
            try stdout.interface.flush();
        },
        .write => try cwd.writeFile(io, .{ .sub_path = rest[1], .data = out.written() }),
    }
    return 0;
}

/// Steward refuses (at compile time) a protocol grain/proto doesn't define;
/// say so here first, with the same words.
fn unknownProtocol(m: schema.Manifest, buf: []u8) ?[]const u8 {
    const names = comptime proto.names();
    const known = struct {
        fn f(n: []const u8) bool {
            for (names) |k| if (std.mem.eql(u8, k, n)) return true;
            return false;
        }
    }.f;
    for (m.domains) |d| {
        for (d.provides) |p| if (!known(p.protocol))
            return std.fmt.bufPrint(buf, "domain '{s}' provides {s}, which is not defined in grain/proto", .{ d.name, p.protocol }) catch "unknown protocol";
        for (d.uses) |u| if (!known(u.protocol))
            return std.fmt.bufPrint(buf, "domain '{s}' uses {s}, which is not defined in grain/proto", .{ d.name, u.protocol }) catch "unknown protocol";
    }
    return null;
}
